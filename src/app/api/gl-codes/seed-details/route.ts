export async function POST(req: Request) {
  const cookieStore = await cookies();
  const token = cookieStore.get("admin_session")?.value || null;
  if (!verifySession(token)) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  try {
    let updated = 0;
    let skipped = 0;

    for (const [code, details] of Object.entries(GL_DETAILS)) {
      const result = await query(
        `UPDATE gl_codes SET details = $1 WHERE gl_code = $2 AND (details IS NULL OR details = '')`,
        [details, code]
      );
      if (result.rowCount && result.rowCount > 0) {
        updated++;
      } else {
        skipped++;
      }
    }

    await addLog(
      "info",
      "gl_details_seed",
      `Seeded Dhivehi details: ${updated} updated, ${skipped} skipped (already had details or code not found)`
    );

    return NextResponse.json({
      success: true,
      updated,
      skipped,
      total: Object.keys(GL_DETAILS).length,
    });
  } catch (error) {
    return NextResponse.json(
      { error: "Failed to seed GL details", detail: String(error) },
      { status: 500 }
    );
  }
}
